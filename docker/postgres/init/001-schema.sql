-- PostgreSQL translation of the supplied DBML. Initialization runs once per empty volume.
BEGIN;

CREATE TYPE visit_task_type AS ENUM ('visit', 'deliver');
CREATE TYPE zone_surface_type AS ENUM ('obstacle', 'restricted', 'no_fly_zone');
CREATE TYPE route_status AS ENUM ('calculated', 'sent_to_robot', 'executing', 'completed', 'failed');

CREATE TABLE roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar NOT NULL UNIQUE,
  label varchar NOT NULL,
  description varchar,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar NOT NULL UNIQUE,
  label varchar NOT NULL,
  description varchar
);

CREATE TABLE role_permissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id integer NOT NULL REFERENCES roles(id),
  permission_id integer NOT NULL REFERENCES permissions(id),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT unique_role_permission UNIQUE (role_id, permission_id)
);

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar NOT NULL UNIQUE CHECK (length(username) >= 3 AND username ~ '^[a-zA-Z0-9_-]+$'),
  email varchar NOT NULL UNIQUE CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  password_hash varchar NOT NULL,
  role_id integer NOT NULL REFERENCES roles(id),
  group_id integer,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE user_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL CHECK (length(name) > 0),
  description varchar,
  leader_id integer NOT NULL REFERENCES users(id),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Add after both tables exist to resolve the circular users/groups reference.
ALTER TABLE users ADD CONSTRAINT users_group_id_fkey FOREIGN KEY (group_id) REFERENCES user_groups(id);

CREATE TABLE scenarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id),
  group_id integer REFERENCES user_groups(id),
  name varchar(255) NOT NULL CHECK (length(name) > 0),
  description varchar,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_public boolean NOT NULL DEFAULT false
);

CREATE TABLE visit_points (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  x decimal(8,6) NOT NULL CHECK (x BETWEEN -21.5 AND 21.5),
  y decimal(8,6) NOT NULL CHECK (y BETWEEN -16.5 AND 16.5),
  task_type visit_task_type NOT NULL DEFAULT 'visit',
  order_index integer NOT NULL CHECK (order_index >= 0),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT unique_scenario_order UNIQUE (scenario_id, order_index)
);

CREATE TABLE limit_zones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  name varchar(255) NOT NULL CHECK (length(name) > 0),
  closed boolean NOT NULL DEFAULT false,
  surface_type zone_surface_type NOT NULL DEFAULT 'obstacle',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE zone_polygon_points (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id integer NOT NULL REFERENCES limit_zones(id),
  x decimal(8,6) NOT NULL CHECK (x BETWEEN -21.5 AND 21.5),
  y decimal(8,6) NOT NULL CHECK (y BETWEEN -16.5 AND 16.5),
  point_order integer NOT NULL CHECK (point_order >= 0),
  CONSTRAINT unique_zone_point_order UNIQUE (zone_id, point_order)
);

CREATE TABLE charging_stations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  x decimal(8,6) NOT NULL CHECK (x BETWEEN -21.5 AND 21.5),
  y decimal(8,6) NOT NULL CHECK (y BETWEEN -16.5 AND 16.5),
  name varchar(255) NOT NULL CHECK (length(name) > 0),
  capacity_kwh decimal(8,2) NOT NULL CHECK (capacity_kwh > 0)
);

CREATE TABLE routes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  user_id integer NOT NULL REFERENCES users(id),
  algorithm varchar(50) NOT NULL CHECK (algorithm IN ('ga_tabu', 'otshig', 'rasseivanie', 'cuckoo')),
  total_distance decimal(10,2) NOT NULL CHECK (total_distance > 0),
  status route_status NOT NULL DEFAULT 'calculated',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  calculated_at timestamp
);

CREATE TABLE route_waypoints (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id integer NOT NULL REFERENCES routes(id),
  x decimal(8,6) NOT NULL CHECK (x BETWEEN -21.5 AND 21.5),
  y decimal(8,6) NOT NULL CHECK (y BETWEEN -16.5 AND 16.5),
  heading_deg decimal(5,2) NOT NULL CHECK (heading_deg >= 0 AND heading_deg < 360),
  order_index integer NOT NULL CHECK (order_index >= 0),
  CONSTRAINT unique_route_order UNIQUE (route_id, order_index)
);

CREATE TABLE telemetry_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id integer NOT NULL REFERENCES routes(id),
  robot_x decimal(8,6) NOT NULL CHECK (robot_x BETWEEN -25 AND 25),
  robot_y decimal(8,6) NOT NULL CHECK (robot_y BETWEEN -20 AND 20),
  robot_z decimal(8,6) NOT NULL DEFAULT 0,
  robot_yaw decimal(5,2) NOT NULL CHECK (robot_yaw >= 0 AND robot_yaw < 360),
  battery_level decimal(5,2) NOT NULL CHECK (battery_level BETWEEN 0 AND 100),
  timestamp timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id),
  entity_type varchar(50) NOT NULL CHECK (entity_type IN ('scenario', 'route', 'user', 'group', 'permission')),
  entity_id integer NOT NULL,
  action varchar(50) NOT NULL CHECK (action IN ('created', 'updated', 'deleted', 'sent_to_robot', 'completed')),
  timestamp timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE lidar_files (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  route_id integer REFERENCES routes(id),
  file_name varchar(255) NOT NULL,
  storage_key varchar(512) NOT NULL,
  file_size_bytes bigint NOT NULL,
  format varchar(20) NOT NULL,
  point_count bigint,
  checksum varchar(128),
  captured_at timestamp NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE maps (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id integer NOT NULL REFERENCES scenarios(id),
  route_id integer REFERENCES routes(id),
  name varchar(255) NOT NULL,
  map_type varchar(30) NOT NULL,
  storage_key varchar(512) NOT NULL,
  resolution float,
  width integer,
  height integer,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  generated_at timestamp NOT NULL
);

-- Index foreign keys that are not already covered by an ordered unique index.
CREATE INDEX role_permissions_permission_idx ON role_permissions (permission_id);
CREATE INDEX users_role_idx ON users (role_id);
CREATE INDEX users_group_idx ON users (group_id);
CREATE INDEX user_groups_leader_idx ON user_groups (leader_id);
CREATE INDEX scenarios_user_idx ON scenarios (user_id);
CREATE INDEX scenarios_group_idx ON scenarios (group_id);
CREATE INDEX limit_zones_scenario_idx ON limit_zones (scenario_id);
CREATE INDEX charging_stations_scenario_idx ON charging_stations (scenario_id);
CREATE INDEX routes_scenario_idx ON routes (scenario_id);
CREATE INDEX routes_user_idx ON routes (user_id);
CREATE INDEX telemetry_logs_route_timestamp_idx ON telemetry_logs (route_id, timestamp);
CREATE INDEX audit_log_user_idx ON audit_log (user_id);
CREATE INDEX lidar_files_scenario_captured_idx ON lidar_files (scenario_id, captured_at);
CREATE INDEX lidar_files_route_captured_idx ON lidar_files (route_id, captured_at);
CREATE INDEX maps_scenario_idx ON maps (scenario_id);
CREATE INDEX maps_route_idx ON maps (route_id);

INSERT INTO roles (code, label) VALUES
  ('admin', 'Administrator'),
  ('group_leader', 'Group leader'),
  ('user', 'User');

COMMIT;
